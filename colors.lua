-- タブバーの配色。status.lua (左右ステータス)・events_tab.lua (タブ)・tabs.lua
-- (地色そのもの) の3者が同じ地色の上に明暗を組むため、値は必ずここに1つだけ置く。
local M = {}

-- バーの地色。本文背景 (黒) より一段明るいスレートにして、バーとペインの
-- 境界が地色の差で分かるようにする。各セクションの色はこの地色を基準に、
-- 明 (ワークスペース) → 中 (日時) → 暗 (地色) の順で段差をつける。
M.BAR = "#232830"

M.WORKSPACE = { bg = "#dfe6ec", fg = "#1b222b" }
M.DATETIME = { bg = "#3b6b78", fg = "#e6f2f5" }

-- モードは文字列だけでなく色でも見分けられるように色相を変える。
-- 中間明度の彩度高めにして、地色ともワークスペース側の無彩色チップとも
-- 混ざらないようにする。
M.MODE = {
  normal_mode = { bg = "#2f9e63", fg = "#f0fbf4" },
  copy_mode = { bg = "#c8912a", fg = "#1f1704" },
  search_mode = { bg = "#c2553a", fg = "#fdeee9" },
}

-- アクティブタブはワークスペース名チップと同色。どちらも「今いる場所」を
-- 指すので系統を揃える。間に日時が挟まるため隣接はしない。
M.TAB_ACTIVE = { bg = "#dfe6ec", fg = "#1b222b" }
M.TAB_INACTIVE = { bg = "#3d4552", fg = "#aab4c0" }

return M
